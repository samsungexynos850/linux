#ifndef __LINUX_MFD_S2MU106_H
#define __LINUX_MFD_S2MU106_H

#include <linux/bits.h>

/* S2MU106 registers */
#define S2MU106_REG_IPINT		0x00
#define S2MU106_REG_CHGR_INT1		0x01
#define S2MU106_REG_CHGR_INT2		0x02
#define S2MU106_REG_CHGR_INT3		0x03
#define S2MU106_REG_IPINT_MASK		0x07
#define S2MU106_REG_CHGR_INT1M		0x08
#define S2MU106_REG_CHGR_INT2M		0x09
#define S2MU106_REG_CHGR_INT3M		0x0a
#define S2MU106_REG_CHGR_STATUS0	0x0e
#define S2MU106_REG_CHGR_STATUS1	0x0f
#define S2MU106_REG_CHGR_STATUS2	0x10
#define S2MU106_REG_CHGR_STATUS3	0x11
#define S2MU106_REG_CHGR_STATUS4	0x12
#define S2MU106_REG_CHGR_STATUS5	0x13
#define S2MU106_REG_CHGR_CTRL0		0x18
#define S2MU106_REG_ID			0xf5
#define S2MU106_REG_MAX			0xff

/* S2MU106_REG_IPINT and S2MU106_REG_IPINT_MASK */
#define S2MU106_IPINT_PM		BIT(0)
#define S2MU106_IPINT_AFC		BIT(1)
#define S2MU106_IPINT_MUIC		BIT(2)
#define S2MU106_IPINT_MST		BIT(3)
#define S2MU106_IPINT_HBST		BIT(4)
#define S2MU106_IPINT_FLED		BIT(5)
#define S2MU106_IPINT_CHGR		BIT(6)
#define S2MU106_IPINT_HAPTIC		BIT(7)

/* S2MU106_REG_CHGR_STATUS0 */
#define S2MU106_CHGR_WCIN_STATUS	GENMASK(6, 4)
#define S2MU106_CHGR_CHGIN_STATUS	GENMASK(2, 0)
#define S2MU106_CHGR_IN_STATUS_VALID	0x3
#define S2MU106_CHGR_IN_STATUS_VALID2	0x5

/* S2MU106_REG_CHGR_STATUS1 */
#define S2MU106_CHGR_FAULT_STATUS	GENMASK(7, 4)
#define S2MU106_CHGR_CV_STATUS		BIT(3)
#define S2MU106_CHGR_RESTART_STATUS	BIT(2)
#define S2MU106_CHGR_TOPOFF_STATUS	BIT(1)
#define S2MU106_CHGR_DONE_STATUS	BIT(0)

#define S2MU106_CHGR_FAULT_NORMAL	0x0
#define S2MU106_CHGR_FAULT_WD_SUSPEND	0x1
#define S2MU106_CHGR_FAULT_WD_RESET	0x2
#define S2MU106_CHGR_FAULT_TSD		0x3
#define S2MU106_CHGR_FAULT_TFB		0x4
#define S2MU106_CHGR_FAULT_PRECHG_TMO	0x6
#define S2MU106_CHGR_FAULT_FASTCHG_TMO	0x7

/* S2MU106_REG_CHGR_STATUS3 */
#define S2MU106_CHGR_BAT_STATUS		GENMASK(3, 1)
#define S2MU106_CHGR_DET_BAT		BIT(0)

/* S2MU106_REG_ID */
#define S2MU106_ID_MASK			GENMASK(3, 0)

#endif /* __LINUX_MFD_S2MU106_H */
